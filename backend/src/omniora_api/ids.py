"""UUIDv7 generation (RFC 9562, section 5.7) with a monotonic counter.

Server-assigned identifiers for every persisted entity. Within one millisecond, the 12-bit
`rand_a` field acts as a counter (RFC 9562 method 1), so ids generated by this process sort in
creation order, which repositories use as a deterministic tie-breaker.
"""

from __future__ import annotations

import secrets
import threading
import time
import uuid

_lock = threading.Lock()
_last_ms = -1
_counter = 0


def uuid7() -> uuid.UUID:
    global _last_ms, _counter
    with _lock:
        ms = time.time_ns() // 1_000_000
        if ms > _last_ms:
            _last_ms = ms
            _counter = secrets.randbits(11)  # leave headroom for increments
        else:
            _counter += 1
            if _counter > 0xFFF:  # counter exhausted: advance the timestamp
                _last_ms += 1
                _counter = secrets.randbits(11)
            ms = _last_ms
        rand_b = secrets.randbits(62)
        value = (ms & 0xFFFF_FFFF_FFFF) << 80
        value |= 0x7 << 76  # version 7
        value |= (_counter & 0xFFF) << 64
        value |= 0b10 << 62  # RFC 4122 variant
        value |= rand_b
    return uuid.UUID(int=value)
